// Search engine setup: per-page canonical and social tags, sitemap.xml and robots.txt.
//
// Every page in public/*.html keeps its own <title> and <meta name="description">.
// This script adds a generated block (between the seo:start and seo:end comments)
// with the canonical URL, Open Graph and Twitter tags built from them, and
// optionally the Google Search Console verification tag.
//
// A page is left out of the sitemap when it carries <meta name="robots" content="noindex">.
// New pages are picked up automatically. Paper and company pages are templates,
// so the sitemap lists one URL per paper and per company from the build's data.
//
//   node scripts/seo.mjs --write   update the head blocks in public/*.html (run after adding a page)
//   node scripts/seo.mjs           build step: also writes public/sitemap.xml and public/robots.txt
//
// Environment:
//   SEO_SITE_URL               canonical address, default https://www.pvinfo.org
//   GOOGLE_SITE_VERIFICATION   optional; the content value of Google's HTML-tag verification method
//
// SEO_SITE_URL is separate from SITE_URL, which the build uses to read the last
// published data and must keep pointing at an address that already serves it.

import { readFile, writeFile, readdir } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const PUBLIC = path.join(ROOT, "public");
export const SEO_SITE_URL = (process.env.SEO_SITE_URL || "https://www.pvinfo.org").replace(/\/$/, "");
const SITE_NAME = "PV Info";
const START = "<!-- seo:start (generated by scripts/seo.mjs; edit the title and description above instead) -->";
const END = "<!-- seo:end -->";
const BLOCK = /[ \t]*<!-- seo:start[^>]*-->[\s\S]*?<!-- seo:end -->\n?/;

// Template pages: the canonical URL gains ?id=... in the browser (public/seo.js).
export const TEMPLATES = { "paper.html": "id", "company.html": "id" };

const decode = (s) => s.replace(/&quot;/g, '"').replace(/&#39;/g, "'").replace(/&lt;/g, "<").replace(/&gt;/g, ">").replace(/&amp;/g, "&");
const esc = (s) => String(s).replace(/&/g, "&amp;").replace(/"/g, "&quot;").replace(/</g, "&lt;").replace(/>/g, "&gt;");

export function pageMeta(html) {
  const title = html.match(/<title>([^<]*)<\/title>/)?.[1]?.trim();
  const description = html.match(/<meta name="description" content="([^"]*)"/)?.[1]?.trim();
  const noindex = /<meta name="robots" content="[^"]*noindex/.test(html);
  return { title: title && decode(title), description: description && decode(description), noindex };
}

export const pagePath = (file) => (file === "index.html" ? "/" : `/${file}`);

export function seoBlock(file, html, { base = SEO_SITE_URL, verification = "" } = {}) {
  const { title, description, noindex } = pageMeta(html);
  const url = base + pagePath(file);
  const lines = [START];
  if (verification && file === "index.html") lines.push(`<meta name="google-site-verification" content="${esc(verification)}">`);
  if (!noindex) lines.push(`<link rel="canonical" href="${esc(url)}">`);
  lines.push(
    `<meta property="og:type" content="website">`,
    `<meta property="og:site_name" content="${SITE_NAME}">`,
    `<meta property="og:title" content="${esc(title ?? SITE_NAME)}">`,
  );
  if (description) lines.push(`<meta property="og:description" content="${esc(description)}">`);
  lines.push(
    `<meta property="og:url" content="${esc(url)}">`,
    `<meta property="og:image" content="${base}/og.png">`,
    `<meta property="og:image:width" content="1200">`,
    `<meta property="og:image:height" content="630">`,
    `<meta name="twitter:card" content="summary_large_image">`,
    END,
  );
  return lines.map((l) => `  ${l}`).join("\n") + "\n";
}

// Puts the block before the stylesheet link (or replaces the existing block).
export function syncHead(file, html, opts) {
  const block = seoBlock(file, html, opts);
  if (BLOCK.test(html)) return html.replace(BLOCK, block);
  const at = html.search(/[ \t]*<link rel="stylesheet"/);
  const i = at >= 0 ? at : html.indexOf("</head>");
  return html.slice(0, i) + block + html.slice(i);
}

export async function listPages(dir = PUBLIC) {
  return (await readdir(dir)).filter((f) => f.endsWith(".html")).sort();
}

// Problems that should fail CI: pages without a title or description.
export function problems(pages) {
  const out = [];
  for (const [file, html] of pages) {
    const m = pageMeta(html);
    if (!m.title) out.push(`${file}: missing <title>`);
    if (!m.noindex && !m.description) out.push(`${file}: missing <meta name="description">`);
  }
  return out;
}

const xml = (s) => String(s).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");

export function sitemap(pages, { base = SEO_SITE_URL, papers = [], companies = [], now = new Date() } = {}) {
  const today = now.toISOString().slice(0, 10);
  const urls = [];
  for (const [file, html] of pages) {
    if (pageMeta(html).noindex) continue;
    if (file === "index.html") urls.push({ loc: `${base}/`, lastmod: today, changefreq: "hourly", priority: "1.0" });
    else urls.push({ loc: base + pagePath(file), changefreq: "daily", priority: "0.7" });
  }
  const indexed = new Set(pages.filter(([, h]) => !pageMeta(h).noindex).map(([f]) => f));
  if (indexed.has("paper.html"))
    for (const p of papers) if (p?.id) urls.push({ loc: `${base}/paper.html?id=${encodeURIComponent(p.id)}`, lastmod: (p.published ?? p.date ?? "").slice(0, 10) || undefined, changefreq: "monthly", priority: "0.5" });
  if (indexed.has("company.html"))
    for (const c of companies) if (c?.id) urls.push({ loc: `${base}/company.html?id=${encodeURIComponent(c.id)}`, changefreq: "daily", priority: "0.5" });
  const body = urls.map((u) => {
    const parts = [`<loc>${xml(u.loc)}</loc>`];
    if (u.lastmod && /^\d{4}-\d{2}-\d{2}$/.test(u.lastmod)) parts.push(`<lastmod>${u.lastmod}</lastmod>`);
    parts.push(`<changefreq>${u.changefreq}</changefreq>`, `<priority>${u.priority}</priority>`);
    return `  <url>${parts.join("")}</url>`;
  });
  return `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${body.join("\n")}\n</urlset>\n`;
}

export function robots({ base = SEO_SITE_URL } = {}) {
  return `User-agent: *\nAllow: /\nDisallow: /api/\n\nSitemap: ${base}/sitemap.xml\n`;
}

async function readJson(file) {
  try { return JSON.parse(await readFile(file, "utf8")); } catch { return null; }
}

export async function run({ write = true, build = false, dir = PUBLIC, env = process.env } = {}) {
  const base = (env.SEO_SITE_URL || "https://www.pvinfo.org").replace(/\/$/, "");
  const verification = (env.GOOGLE_SITE_VERIFICATION || "").trim();
  const pages = [];
  for (const file of await listPages(dir)) {
    const html = await readFile(path.join(dir, file), "utf8");
    // The verification tag is only added on the build machine, so the committed files stay token-free.
    const next = syncHead(file, html, { base, verification: build ? verification : "" });
    if (write && next !== html) await writeFile(path.join(dir, file), next);
    pages.push([file, next]);
  }
  const issues = problems(pages);
  if (build) {
    const research = await readJson(path.join(dir, "data/research.json"));
    const companies = await readJson(path.join(dir, "data/companies/index.json"));
    const map = sitemap(pages, { base, papers: research?.papers ?? [], companies: companies?.companies ?? [] });
    await writeFile(path.join(dir, "sitemap.xml"), map);
    await writeFile(path.join(dir, "robots.txt"), robots({ base }));
    console.log(`seo: sitemap.xml with ${(map.match(/<url>/g) ?? []).length} URLs for ${base}${verification ? " (Google verification tag on)" : ""}`);
  }
  return { pages, issues };
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  const build = !process.argv.includes("--write");
  const { issues } = await run({ build });
  for (const i of issues) console.warn(`seo: ${i}`);
}
