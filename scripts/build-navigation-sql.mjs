import {readFile,writeFile} from 'node:fs/promises';
import {PAGES} from '../public/navigation.js';
const base=await readFile('supabase/migrations/20261106012533_content_studio_navigation.sql','utf8');
const known=Object.keys(PAGES).map(x=>"'"+x+"'").join(',');
const sql=base.replace(/known text\[\]:=array\[[^\]]*\]/,'known text[]:=array['+known+']').replace("'e2b-studio','content-studio']))", "'e2b-studio','content-studio','sandbox','rule-templates','product-answers','label-analysis']))");
await writeFile('supabase/navigation-registry.sql',sql);
const marker='-- Current navigation registry (generated by scripts/build-navigation-sql.mjs).';
const schema=(await readFile('supabase/schema.sql','utf8')).split(marker)[0];
await writeFile('supabase/schema.sql',schema+'\n'+marker+'\n'+sql);
